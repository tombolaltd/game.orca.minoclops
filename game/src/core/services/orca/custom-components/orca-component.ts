/**
 * Orca custom component — authoring contract.
 *
 * Drop a TypeScript file next to this one (in this project's
 * orca-project-files/components/ folder) and it becomes a component you can
 * attach to any scene node from the Inspector. A component file must export
 * exactly two things:
 *
 *   1. "definition" — a plain object literal describing the component and the
 *      properties the Inspector should show.
 *   2. a DEFAULT-EXPORTED class extending OrcaComponent — the behaviour.
 *
 * THE DEFINITION IS PARSED, NEVER EXECUTED. Orca reads the object literal
 * statically (no TypeScript compiler, no eval), so every value in it must be a
 * literal: strings, numbers, booleans, null, arrays and nested objects only.
 * No function calls, no imported constants, no template interpolation.
 *
 * KEY RULES
 *
 * - "name" is the IMMUTABLE RUNTIME KEY. It is what a scene stores against the
 *   node and what the runtime resolves. Renaming it detaches the component
 *   from every node already using it — change "friendlyTitle" instead for a
 *   cosmetic relabel. It must be a valid identifier and unique per project.
 * - The FILE NAME does not have to match "name" — "name" always wins.
 * - Every property needs a "type". A property with no "default" gets a
 *   type-appropriate one ('' / 0 / false / { x: 0, y: 0 } / the first enum
 *   option).
 * - An 'enum' property MUST declare a non-empty "options" string array, and no
 *   other property type may declare one.
 * - "target" picks which scene nodes can use the component: '2d' (the
 *   default when omitted) for 2D nodes, '3d' for 3D nodes (camera3d / group3d /
 *   model3d / light3d), or 'any' for both.
 * - CONSTRUCTORS TAKE NO ARGUMENTS. Orca instantiates your class with "new
 *   YourComponent()" and then calls __orcaInit to inject "node",
 *   "displayObject", "object3d", "properties" and "orca". Declaring a
 *   constructor with required parameters, or overriding __orcaInit, WILL
 *   BREAK INSTANTIATION.
 *   Put your setup in onCreate, which runs after injection.
 *
 * WORKED EXAMPLE — save as components/Spinner.ts:
 *
 *   import { OrcaComponent } from './orca-component';
 *   import type { OrcaComponentDefinition } from './orca-component';
 *
 *   export const definition: OrcaComponentDefinition = {
 *     name: 'Spinner',
 *     friendlyTitle: 'Spinner',
 *     description: 'Rotates the node it is attached to.',
 *     icon: '🌀',
 *     properties: [
 *       { name: 'speed', type: 'float', default: 90, description: 'Degrees per second' },
 *       { name: 'clockwise', type: 'bool', default: true },
 *       { name: 'easing', type: 'enum', options: ['linear', 'smooth'], default: 'linear' }
 *     ]
 *   };
 *
 *   export default class Spinner extends OrcaComponent {
 *     private direction = 1;
 *
 *     onCreate(): void {
 *       this.direction = this.getProperty('clockwise', true) ? 1 : -1;
 *     }
 *
 *     onUpdate(deltaMs: number): void {
 *       const degreesPerSecond = this.getProperty('speed', 0);
 *       this.displayObject.rotation +=
 *         (degreesPerSecond * Math.PI / 180) * (deltaMs / 1000) * this.direction;
 *     }
 *
 *     onDestroy(): void {
 *       // Release anything you allocated in onCreate.
 *     }
 *   }
 *
 * LIFECYCLE
 *
 *   onCreate()          once, after the node and its children have been built
 *   onUpdate(deltaMs)   every frame, with elapsed milliseconds
 *   onDestroy()         when the node is destroyed or its scene is unloaded
 *
 * All three are optional — implement only what you need.
 *
 * WHERE THIS CODE RUNS: your component is compiled INTO THE GAME, not into the
 * editor. It may import anything the game can import (relative paths resolve
 * against game/src/core/services/orca/custom-components/, the folder Orca
 * mirrors this one into). Keep it side-effect free at module scope — it is
 * imported eagerly at game start.
 *
 * DO NOT EDIT this file: it is regenerated by Orca. Editing it will be undone.
 */

/**
 * Property types a component property may declare.
 *
 * An 'assetRef' is AUTHORED as a bucket-relative asset path, but it ARRIVES IN
 * "properties" AT RUNTIME ALREADY RESOLVED to an OrcaTexture (or null when no
 * asset is set). PIXI loads textures asynchronously, so the texture may not be
 * "valid" yet during onCreate: assigning it to a sprite is safe, but reading
 * "width" / "height" that early may give 0.
 *
 * On a 3D host an 'assetRef' property instead resolves to the asset's runtime
 * URL STRING (or null), not a texture — load it yourself, e.g. with
 * "this.orca.three".
 *
 * A 'customEventRef' is picked from the project's custom events in the
 * Inspector and arrives as the plain event NAME — the string you pass to
 * "this.orca.on(...)" / "this.orca.emit(...)". It is empty when nothing is
 * selected, and keeps its value if the event is later renamed or deleted.
 *
 * Any other name is one of the project's Custom Types (Data Browser ▸ Types):
 * an enum arrives as its member string, a struct as a plain object. Import
 * them from './orca-types'.
 */
export type OrcaComponentPropertyType =
  | 'string' | 'int' | 'float' | 'bool' | 'color' | 'vector2' | 'enum' | 'assetRef'
  | 'customEventRef' | (string & {});

/** One authored property, surfaced as a field in the Inspector. */
export interface OrcaComponentPropertyDef {
  /** Identifier-shaped and unique within this component. */
  name: string;
  type: OrcaComponentPropertyType;
  /** Filled in with a type-appropriate value when omitted. */
  default?: unknown;
  /** Required (and only valid) when type is 'enum'. */
  options?: string[];
  /** Tooltip text shown next to the field. */
  description?: string;
}

/** The object literal a custom component file must export as "definition". */
export interface OrcaComponentDefinition {
  /** Immutable runtime key. Must be a valid identifier and unique per project. */
  name: string;
  /** Cosmetic label shown in the Inspector. Safe to change. */
  friendlyTitle?: string;
  /** Tooltip / docs text. */
  description?: string;
  /** Emoji or short glyph shown beside the component. */
  icon?: string;
  /** Where it can attach: '2d' (default when omitted), '3d' or 'any'. */
  target?: '2d' | '3d' | 'any';
  properties?: OrcaComponentPropertyDef[];
}

/** A plain 2D vector, the shape a 'vector2' property resolves to. */
export interface OrcaVector2 { x: number; y: number; }

/**
 * Structural view of the live PIXI display object backing the node.
 *
 * Typed structurally (rather than as a real PIXI type) so this file can stay
 * import-free. Cast to the PIXI type you need if you want the full surface:
 * "const sprite = this.displayObject as unknown as PIXI.Sprite;".
 */
export interface OrcaDisplayObject {
  x: number;
  y: number;
  alpha: number;
  visible: boolean;
  rotation: number;
  position: { x: number; y: number; set(x: number, y?: number): void };
  scale: { x: number; y: number; set(x: number, y?: number): void };
  pivot: { x: number; y: number; set(x: number, y?: number): void };
  width: number;
  height: number;
  name: string | null;
  parent: OrcaDisplayObject | null;
  children?: OrcaDisplayObject[];
  [key: string]: any;
}

/**
 * Structural view of the live three.js Object3D backing a 3D scene node.
 *
 * Typed structurally so this file can stay import-free. Cast for the full
 * surface: "const mesh = this.object3d as unknown as THREE.Mesh;".
 */
export interface OrcaObject3D {
  name: string;
  visible: boolean;
  position: { x: number; y: number; z: number; set(x: number, y: number, z: number): void };
  /** Euler angles in RADIANS. */
  rotation: { x: number; y: number; z: number; set(x: number, y: number, z: number): void };
  scale: { x: number; y: number; z: number; set(x: number, y: number, z: number): void };
  parent: OrcaObject3D | null;
  children: OrcaObject3D[];
  userData: Record<string, any>;
  add(...objects: any[]): any;
  remove(...objects: any[]): any;
  [key: string]: any;
}

/**
 * Structural view of a loaded texture — the shape an 'assetRef' property
 * resolves to (on a 2D host) by the time it reaches "properties".
 *
 * Typed structurally (rather than as a real PIXI type) so this file can stay
 * import-free. Cast if you want the full surface:
 * "const texture = this.getProperty<OrcaTexture>('image') as unknown as PIXI.Texture;".
 *
 * "valid" is false until PIXI has finished loading the underlying image, which
 * can still be pending during onCreate.
 */
export interface OrcaTexture {
  width: number;
  height: number;
  valid: boolean;
  [key: string]: any;
}

/** Serialized scene-node data backing this component's node. */
export interface OrcaComponentNode {
  id: string;
  name: string;
  type: string;
  [key: string]: any;
}

/** Everything the component can reach in the wider game. Injected by Orca. */
export interface OrcaComponentContext {
  getGameModelProperty(propertyName: string): unknown;
  setGameModelProperty(propertyName: string, value: unknown): void;
  getSettingsModelProperty(propertyName: string): unknown;
  setSettingsModelProperty(propertyName: string, value: unknown): void;
  /** Subscribe to an Orca custom event or any built-in game event. Auto-removed on destroy. */
  on(eventName: string, handler: (payload?: any) => void): void;
  off(eventName: string, handler: (payload?: any) => void): void;
  /** Fire an Orca custom event. Payload must be a plain object keyed by the event's pass-props. */
  emit(eventName: string, payload?: Record<string, unknown>): void;
  /** Resolve another scene node's live display object by its node id. */
  getDisplayObjectById(nodeId: string): OrcaDisplayObject | null;
  /** Resolve another 3D scene node's live Object3D by its node id. 3D hosts only. */
  getObject3DById?(nodeId: string): OrcaObject3D | null;
  /** The loaded THREE namespace (this folder cannot import three). 3D hosts only. */
  three?: any;
  /** Load a scene by name. */
  loadScene(name: string, scope?: 'core' | 'skin'): void;
  /** Unload a scene by name, or the current one when omitted. */
  unloadScene(name?: string, scope?: 'core' | 'skin'): void;
}

/**
 * Base class every custom component extends.
 *
 * Instantiated by Orca with NO constructor arguments; the protected
 * fields below are injected immediately afterwards by __orcaInit. Do not
 * declare a constructor with required parameters and do not override
 * __orcaInit — either will break instantiation. Use onCreate for setup.
 */
export abstract class OrcaComponent {
  /** The scene node this component is attached to. */
  protected node!: OrcaComponentNode;

  /** The live display object for that node. On a 3D host it is the same object as "object3d" — prefer "object3d" for 3D typing. */
  protected displayObject!: OrcaDisplayObject;

  /** The live three.js Object3D on a 3D host; null on a 2D host. */
  protected object3d!: OrcaObject3D | null;

  /** Authored property values, merged over the definition defaults. */
  protected properties!: Record<string, any>;

  /** Data model + event access. */
  protected orca!: OrcaComponentContext;

  /** Called once, after the node and its children have been built. */
  onCreate?(): void;

  /** Called every frame. "deltaMs" is elapsed milliseconds since the previous frame. */
  onUpdate?(deltaMs: number): void;

  /** Called when the node is destroyed or its scene is unloaded. */
  onDestroy?(): void;

  /**
   * Typed property read with a fallback.
   *
   * Returns "fallback" when the property was never authored and has no
   * resolved default (i.e. the stored value is undefined or null).
   */
  protected getProperty<T = unknown>(name: string, fallback?: T): T {
    const bag = this.properties;
    if (bag && Object.prototype.hasOwnProperty.call(bag, name)) {
      const value = bag[name];
      if (value !== undefined && value !== null) return value as T;
    }
    return fallback as T;
  }

  /** @internal — called by Orca immediately after construction. Do not call or override. */
  __orcaInit(
    node: OrcaComponentNode,
    displayObject: OrcaDisplayObject,
    properties: Record<string, any>,
    context: OrcaComponentContext,
    object3d?: OrcaObject3D | null,
  ): void {
    this.node = node;
    this.displayObject = displayObject;
    this.properties = properties || {};
    this.orca = context;
    this.object3d = object3d ?? null;
  }
}
