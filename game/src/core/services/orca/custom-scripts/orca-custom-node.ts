/**
 * Orca custom FlowState node — authoring contract.
 *
 * Drop a TypeScript file next to this one (in this project's
 * orca-project-files/scripts/ folder) and it becomes a node in the FlowState
 * node menu. A script file must export exactly two things:
 *
 *   1. "definition" — a plain object literal describing the node.
 *   2. "run"        — the function the node executes. May be async.
 *
 * THE DEFINITION IS PARSED, NEVER EXECUTED. Orca reads the object literal
 * statically (no TypeScript compiler, no eval), so every value in it must be a
 * literal: strings, numbers, booleans, null, arrays and nested objects only.
 * No function calls, no imported constants, no template interpolation.
 *
 * KEY RULES
 *
 * - "name" is the IMMUTABLE RUNTIME KEY. It is what the graph stores and what
 *   the runtime walker resolves. Renaming it breaks every graph already using
 *   the node — change "friendlyTitle" instead for a cosmetic relabel. It must
 *   be a valid identifier and must not clash with another node's name.
 * - The FILE NAME does not have to match "name" — "name" always wins.
 * - "inputs" map to run's POSITIONAL parameters, in declared order. The first
 *   input is the first parameter, the second is the second, and so on.
 * - OUTPUTS decide what the node is:
 *     0 outputs  -> action node. run returns void (anything returned is ignored).
 *     1 output   -> value node. run returns THE VALUE itself.
 *     2+ outputs -> value node. run returns an OBJECT keyed by each output name.
 *   Declaring any output forces nodeType to 'property' automatically.
 * - "run" may be async; the walker awaits it.
 *
 * WORKED EXAMPLE — save as scripts/rollDice.ts:
 *
 *   import type { CustomNodeDefinition } from './orca-custom-node';
 *
 *   export const definition: CustomNodeDefinition = {
 *     name: 'rollDice',
 *     friendlyTitle: 'Roll Dice',
 *     description: 'Rolls a die and reports the face plus whether it was a six.',
 *     icon: '🎲',
 *     color: '#8e44ad',
 *     nodeType: 'property',
 *     inputs: [
 *       { name: 'sides', type: 'int', default: 6, description: 'Number of faces' },
 *       { name: 'lucky', type: 'bool', default: false }
 *     ],
 *     outputs: [
 *       { name: 'face', type: 'int' },
 *       { name: 'isSix', type: 'bool' }
 *     ]
 *   };
 *
 *   export async function run(sides: number, lucky: boolean) {
 *     const face = lucky ? sides : 1 + Math.floor(Math.random() * sides);
 *     return { face, isSix: face === 6 };
 *   }
 *
 * An ACTION node is the same minus outputs:
 *
 *   export const definition: CustomNodeDefinition = {
 *     name: 'logMessage',
 *     friendlyTitle: 'Log Message',
 *     nodeType: 'sequence',
 *     inputs: [{ name: 'message', type: 'string', default: '' }],
 *     outputs: []
 *   };
 *
 *   export function run(message: string): void {
 *     console.log('[logMessage]', message);
 *   }
 *
 * WHERE THIS CODE RUNS: your script is compiled INTO THE GAME, not into the
 * editor. It may import anything the game can import (relative paths resolve
 * against game/src/core/services/orca/custom-scripts/, the folder Orca mirrors
 * this one into). Keep it side-effect free at module scope — it is imported
 * eagerly at game start.
 *
 * DO NOT EDIT this file: it is regenerated by Orca. Editing it will be undone.
 */

/** Pin types a custom node input or output may declare. */
export type CustomNodeIoType =
  | 'string' | 'int' | 'float' | 'bool' | 'any'
  | 'object' | 'nodeRef' | 'audioRef' | 'sceneRef';

/** One input pin. Maps to a POSITIONAL parameter of run, in declared order. */
export interface CustomNodeInput {
  name: string;
  type: CustomNodeIoType;
  default?: string | number | boolean | null;
  description?: string;
}

/** One value output pin. See the "OUTPUTS decide what the node is" rule above. */
export interface CustomNodeOutput { name: string; type: CustomNodeIoType; }

/** The object literal a custom node script must export as `definition`. */
export interface CustomNodeDefinition {
  /** Immutable runtime key. Must be a valid identifier and unique per project. */
  name: string;
  /** Cosmetic label shown in the node menu / on the node. Safe to change. */
  friendlyTitle?: string;
  /** Tooltip / docs text. */
  description?: string;
  /** Emoji or short glyph shown on the node. */
  icon?: string;
  /** Hex colour for the node header, e.g. '#8e44ad'. */
  color?: string;
  /** 'sequence' = action node, 'property' = value node. Forced to 'property' when outputs exist. */
  nodeType?: 'sequence' | 'property';
  inputs?: CustomNodeInput[];
  outputs?: CustomNodeOutput[];
}
